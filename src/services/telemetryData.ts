export function calculateTelemetrySummary(
  calls: CallRecord[],
  speedItems: LeadScheduleSpeedItem[],
  cadenceRelations: LeadTaskCadenceRelation[],
  sdrIdFilter?: string
): AdminTelemetrySummary {
  const filteredCalls = sdrIdFilter ? calls.filter(c => c.sdrId === sdrIdFilter) : calls;
  const filteredSpeed = sdrIdFilter ? speedItems.filter(s => s.sdrId === sdrIdFilter) : speedItems;
  const filteredCadence = sdrIdFilter ? cadenceRelations.filter(c => c.sdrId === sdrIdFilter) : cadenceRelations;

  // 1. Chamadas
  const totalCallsDialed = filteredCalls.length;
  const connectedCalls = filteredCalls.filter(c => c.status === 'CONNECTED');
  const totalCallsConnected = connectedCalls.length;
  const connectRatePercent = totalCallsDialed > 0 
    ? Math.round((totalCallsConnected / totalCallsDialed) * 100) 
    : 0;

  const totalTalkSeconds = connectedCalls.reduce((acc, c) => acc + c.durationSeconds, 0);
  const totalTalkTimeMinutes = Math.round(totalTalkSeconds / 60);
  const avgTalkTimeSeconds = totalCallsConnected > 0 
    ? Math.round(totalTalkSeconds / totalCallsConnected) 
    : 0;

  const scheduledCalls = filteredCalls.filter(c => c.outcome === 'CONNECTED_SCHEDULED');
  const callsScheduledCount = scheduledCalls.length;

  const outcomeDefinitions: { outcome: CallOutcome; label: string; isConnected: boolean }[] = [
    { outcome: 'CONNECTED_SCHEDULED', label: 'Conectada & Reunião Agendada', isConnected: true },
    { outcome: 'CONNECTED_FOLLOWUP', label: 'Conectada & Follow-up Marcado', isConnected: true },
    { outcome: 'CONNECTED_NO_FIT', label: 'Conectada & Sem Perfil (Desqualificado)', isConnected: true },
    { outcome: 'NO_ANSWER', label: 'Não Atende / Tocou até cair', isConnected: false },
    { outcome: 'VOICEMAIL', label: 'Caixa Postal / Secretária', isConnected: false },
    { outcome: 'BUSY_REJECTED', label: 'Ocupado / Recusada', isConnected: false },
    { outcome: 'INVALID_NUMBER', label: 'Número Inválido / Inexistente', isConnected: false },
  ];

  const outcomesBreakdown = outcomeDefinitions.map(def => {
    const count = filteredCalls.filter(c => c.outcome === def.outcome).length;
    const percent = totalCallsDialed > 0 ? Math.round((count / totalCallsDialed) * 100) : 0;
    return {
      outcome: def.outcome,
      label: def.label,
      count,
      percent,
      isConnected: def.isConnected,
    };
  });

  // 2. Tempo para Agendar Lead
  const totalSpeedMinutes = filteredSpeed.reduce((acc, s) => acc + s.timeToScheduleMinutes, 0);
  const avgTimeToScheduleMinutes = filteredSpeed.length > 0 
    ? Math.round(totalSpeedMinutes / filteredSpeed.length) 
    : 0;

  const formatMinutes = (mins: number) => {
    if (mins < 60) return `${mins}m`;
    const h = Math.floor(mins / 60);
    const m = mins % 60;
    return m > 0 ? `${h}h ${m}m` : `${h}h`;
  };

  const sortedSpeeds = [...filteredSpeed].map(s => s.timeToScheduleMinutes).sort((a, b) => a - b);
  const medianTimeToScheduleMinutes = sortedSpeeds.length > 0
    ? sortedSpeeds[Math.floor(sortedSpeeds.length / 2)]
    : 0;

  const fastestTimeToScheduleFormatted = sortedSpeeds.length > 0
    ? formatMinutes(sortedSpeeds[0])
    : '0m';

  const speedCategories: { category: string; label: string; description: string; filterFn: (m: number) => boolean }[] = [
    { category: 'SPEED_ULTRA_FAST', label: 'Ultra-Rápido (< 30 min)', description: 'Agendamento imediato em D0 com contato em minutos', filterFn: m => m <= 30 },
    { category: 'SPEED_SAME_DAY', label: 'Mesmo Dia (30 min a 4h)', description: 'Agendado no mesmo turno/expediente da chegada', filterFn: m => m > 30 && m <= 240 },
    { category: 'SPEED_NEXT_DAY', label: 'D+1 (4h a 24h)', description: 'Agendado no primeiro follow-up ou fila do dia seguinte', filterFn: m => m > 240 && m <= 1440 },
    { category: 'SPEED_LONG_CYCLE', label: 'Cadência Longa (> 24h)', description: 'Múltiplos toques e persistência comercial necessária', filterFn: m => m > 1440 },
  ];

  const speedDistribution = speedCategories.map(cat => {
    const count = filteredSpeed.filter(s => cat.filterFn(s.timeToScheduleMinutes)).length;
    const percent = filteredSpeed.length > 0 ? Math.round((count / filteredSpeed.length) * 100) : 0;
    return {
      category: cat.category,
      label: cat.label,
      description: cat.description,
      count,
      percent,
    };
  });

  // 3. Tarefas vs Data de Criação do Lead
  const totalFirstTouchMins = filteredCadence.reduce((acc, c) => acc + c.firstTouchSlaMinutes, 0);
  const avgFirstTouchSlaMinutes = filteredCadence.length > 0 
    ? Math.round(totalFirstTouchMins / filteredCadence.length) 
    : 0;

  const metSlaCount = filteredCadence.filter(c => c.firstTouchSlaStatus === 'MET').length;
  const firstTouchSlaCompliancePercent = filteredCadence.length > 0 
    ? Math.round((metSlaCount / filteredCadence.length) * 100) 
    : 0;

  // Distribution by Lead Age Buckets
  const ageBuckets: { ageBucket: 'D0' | 'D1' | 'D2' | 'D3' | 'D5_PLUS'; label: string; description: string; filterFn: (days: number) => boolean }[] = [
    { ageBucket: 'D0', label: 'Dia 0 (Chegada Hoje)', description: 'Leads criados há menos de 24 horas', filterFn: d => d === 0 },
    { ageBucket: 'D1', label: 'D+1 (24h - 48h)', description: 'Leads criados ontem (Fila D-1 e 2º toque)', filterFn: d => d === 1 },
    { ageBucket: 'D2', label: 'D+2 (48h - 72h)', description: 'Cadência ativa em andamento', filterFn: d => d === 2 },
    { ageBucket: 'D3', label: 'D+3 (72h - 96h)', description: 'Mapeamento e toques alternativos', filterFn: d => d === 3 || d === 4 },
    { ageBucket: 'D5_PLUS', label: 'D+5 ou mais', description: 'Leads em esteira longa de recuperação/reativação', filterFn: d => d >= 5 },
  ];

  const tasksByLeadAgeDistribution = ageBuckets.map(b => {
    const leadsInBucket = filteredCadence.filter(c => b.filterFn(c.leadAgeDays));
    const tasksInBucket = leadsInBucket.flatMap(l => l.tasksList);
    const completedCount = tasksInBucket.filter(t => t.status === 'COMPLETED').length;
    const overdueCount = leadsInBucket.reduce((acc, l) => acc + l.overdueTasksCount, 0);

    return {
      ageBucket: b.ageBucket,
      label: b.label,
      description: b.description,
      tasksCount: tasksInBucket.length,
      completedCount,
      overdueCount,
      leadsCount: leadsInBucket.length,
    };
  });

  return {
    totalCallsDialed,
    totalCallsConnected,
    connectRatePercent,
    totalTalkTimeMinutes,
    avgTalkTimeSeconds,
    callsScheduledCount,
    outcomesBreakdown,
    avgTimeToScheduleMinutes,
    avgTimeToScheduleFormatted: formatMinutes(avgTimeToScheduleMinutes),
    medianTimeToScheduleMinutes,
    fastestTimeToScheduleFormatted,
    speedDistribution,
    avgFirstTouchSlaMinutes,
    firstTouchSlaCompliancePercent,
    tasksByLeadAgeDistribution,
  };
}
